package com.example.clientdemopublicqa.api;

import java.io.IOException;
import java.io.InputStream;
import java.util.Properties;

/**
 * Minimal configuration holder for API smoke tests.
 * Load from a {@code .properties} resource file on the test classpath via
 * {@link #load(String)}.
 *
 * <p>Override resolution order for every field, highest first:
 * <ol>
 *   <li>JVM system property: {@code api.baseUrl} / {@code api.timeoutSeconds} /
 *       {@code api.healthPath} (e.g. {@code mvn -Dapi.baseUrl=...}).</li>
 *   <li>Environment variable: {@code QAFF_API_BASE_URL} /
 *       {@code QAFF_API_TIMEOUT_SECONDS} / {@code QAFF_API_HEALTH_PATH}.</li>
 *   <li>Value declared in the loaded properties file.</li>
 *   <li>Built-in default ({@value #LOCAL} = in-process stub /
 *       {@value #DEFAULT_TIMEOUT_SECONDS} / {@code /health}).</li>
 * </ol>
 *
 * Generated by qaff (Quality Impact Pack).
 */
public record ApiConfig(String baseUrl, int timeoutSeconds, String healthPath) {

    /** {@code api.baseUrl} value meaning "start the in-process stub" (offline default). */
    public static final String LOCAL = "local";

    private static final int DEFAULT_TIMEOUT_SECONDS = 10;
    private static final String DEFAULT_BASE_URL = LOCAL;
    private static final String DEFAULT_HEALTH_PATH = "/health";
    private static final String ENV_BASE_URL = "QAFF_API_BASE_URL";
    private static final String ENV_TIMEOUT_SECONDS = "QAFF_API_TIMEOUT_SECONDS";
    private static final String ENV_HEALTH_PATH = "QAFF_API_HEALTH_PATH";
    private static final String SYSPROP_BASE_URL = "api.baseUrl";
    private static final String SYSPROP_TIMEOUT_SECONDS = "api.timeoutSeconds";
    private static final String SYSPROP_HEALTH_PATH = "api.healthPath";

    /** True when the smoke should run against its in-process stub instead of a real URL. */
    public boolean isLocal() {
        return LOCAL.equalsIgnoreCase(baseUrl);
    }

    /**
     * Loads an {@link ApiConfig} from the named classpath resource, applying
     * the override resolution order documented on the type.
     *
     * @param resourceName resource name, e.g. {@code "api-config.properties"}
     * @return populated config
     * @throws IllegalStateException if the resource is absent or unreadable
     */
    public static ApiConfig load(String resourceName) {
        try (InputStream in = ApiConfig.class.getClassLoader().getResourceAsStream(resourceName)) {
            if (in == null) {
                throw new IllegalStateException("ApiConfig resource not found: " + resourceName);
            }
            Properties props = new Properties();
            props.load(in);
            String baseUrl = resolveString(
                    SYSPROP_BASE_URL,
                    ENV_BASE_URL,
                    props.getProperty("api.baseUrl"),
                    DEFAULT_BASE_URL);
            int timeoutSeconds = resolveInt(
                    SYSPROP_TIMEOUT_SECONDS,
                    ENV_TIMEOUT_SECONDS,
                    props.getProperty("api.timeoutSeconds"),
                    DEFAULT_TIMEOUT_SECONDS);
            String healthPath = resolveString(
                    SYSPROP_HEALTH_PATH,
                    ENV_HEALTH_PATH,
                    props.getProperty("api.healthPath"),
                    DEFAULT_HEALTH_PATH);
            return new ApiConfig(baseUrl, timeoutSeconds, healthPath);
        } catch (IOException e) {
            throw new IllegalStateException("Failed to load ApiConfig from: " + resourceName, e);
        }
    }

    private static String resolveString(
            String sysProp,
            String envVar,
            String fileValue,
            String defaultValue) {
        String sys = System.getProperty(sysProp);
        if (sys != null && !sys.isBlank()) {
            return sys.trim();
        }
        String env = System.getenv(envVar);
        if (env != null && !env.isBlank()) {
            return env.trim();
        }
        if (fileValue != null && !fileValue.isBlank()) {
            return fileValue.trim();
        }
        return defaultValue;
    }

    private static int resolveInt(
            String sysProp,
            String envVar,
            String fileValue,
            int defaultValue) {
        String raw = resolveString(sysProp, envVar, fileValue, null);
        if (raw == null) {
            return defaultValue;
        }
        return Integer.parseInt(raw);
    }
}
